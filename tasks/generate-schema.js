/**
 * Generates the DMN 1.5 moddle schemas in `src/moddle/` from the
 * DMN 1.3 schemas shipped with dmn-moddle.
 *
 * DMN 1.4 / 1.5 are (mostly) additive to DMN 1.3; the delta is:
 *
 *   - <itemDefinition> gained <typeConstraint>
 *   - boxed <conditional>, <filter>, <for>, <every> and <some> expressions
 *   - <dmndi:DMNDiagram> gained @useAlternativeInputDataShape
 *
 * Usage: node tasks/generate-schema.js
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);

const DMN15_URI = 'https://www.omg.org/spec/DMN/20230324/MODEL/';
const DMNDI15_URI = 'https://www.omg.org/spec/DMN/20230324/DMNDI/';

const resources = dirname(require.resolve('dmn-moddle/resources/dmn/json/dmn13.json'));

const dmn = JSON.parse(readFileSync(resolve(resources, 'dmn13.json'), 'utf8'));
const dmndi = JSON.parse(readFileSync(resolve(resources, 'dmndi13.json'), 'utf8'));


// DMN ////////////

dmn.uri = DMN15_URI;

const itemDefinition = dmn.types.find(t => t.name === 'ItemDefinition');

itemDefinition.properties.splice(2, 0, {
  name: 'typeConstraint',
  type: 'UnaryTests',
  xml: {
    serialize: 'property'
  }
});

dmn.types.push(
  {
    name: 'ChildExpression',
    properties: [
      { name: 'id', type: 'String', isAttr: true, isId: true },
      { name: 'expression', type: 'Expression' }
    ]
  },
  {
    name: 'TypedChildExpression',
    superClass: [ 'ChildExpression' ],
    properties: [
      { name: 'typeRef', type: 'String', isAttr: true }
    ]
  },
  {
    name: 'Iterator',
    isAbstract: true,
    superClass: [ 'Expression' ],
    properties: [
      { name: 'in', type: 'TypedChildExpression', xml: { serialize: 'property' } },
      { name: 'iteratorVariable', type: 'String', isAttr: true }
    ]
  },
  {
    name: 'For',
    superClass: [ 'Iterator' ],
    properties: [
      { name: 'return', type: 'ChildExpression', xml: { serialize: 'property' } }
    ]
  },
  {
    name: 'Quantified',
    isAbstract: true,
    superClass: [ 'Iterator' ],
    properties: [
      { name: 'satisfies', type: 'ChildExpression', xml: { serialize: 'property' } }
    ]
  },
  {
    name: 'Every',
    superClass: [ 'Quantified' ]
  },
  {
    name: 'Some',
    superClass: [ 'Quantified' ]
  },
  {
    name: 'Conditional',
    superClass: [ 'Expression' ],
    properties: [
      { name: 'if', type: 'ChildExpression', xml: { serialize: 'property' } },
      { name: 'then', type: 'ChildExpression', xml: { serialize: 'property' } },
      { name: 'else', type: 'ChildExpression', xml: { serialize: 'property' } }
    ]
  },
  {
    name: 'Filter',
    superClass: [ 'Expression' ],
    properties: [
      { name: 'in', type: 'ChildExpression', xml: { serialize: 'property' } },
      { name: 'match', type: 'ChildExpression', xml: { serialize: 'property' } }
    ]
  }
);


// DMNDI ////////////

dmndi.uri = DMNDI15_URI;

const dmnDiagram = dmndi.types.find(t => t.name === 'DMNDiagram');

dmnDiagram.properties.push({
  name: 'useAlternativeInputDataShape',
  type: 'Boolean',
  isAttr: true,
  default: false
});


// write ////////////

const target = resolve(dirname(new URL(import.meta.url).pathname), '../src/moddle');

mkdirSync(target, { recursive: true });

write('dmn15.js', dmn);
write('dmndi15.js', dmndi);

function write(file, schema) {
  const contents = [
    '// generated by tasks/generate-schema.js, do not edit',
    '',
    `export default ${ JSON.stringify(schema, null, 2) };`,
    ''
  ].join('\n');

  writeFileSync(resolve(target, file), contents, 'utf8');

  console.log(`wrote src/moddle/${ file }`);
}
